/**
 * Generates src/viz/bodyPaths.ts -- the body outlines the Recovery map draws.
 *
 * The geometry is MuscleMap by Melih Colpan (MIT), which ships its paths as
 * Swift source rather than .svg files. This script reads those Swift files at a
 * PINNED commit, so re-running it is byte-stable, and writes one TS module.
 *
 * What is kept, and why:
 *   - Whole muscles, plus the three parts MuscleMap draws even with sub-groups
 *     hidden (adductors, neck, ankles) and the rotator cuff, which is carved out
 *     of the upper back rather than laid over it.
 *   - Non-muscle parts (head, hair, hands, feet, knees, tibialis) as silhouette.
 *   - Sub-groups (upper-chest, outer-quad, front-deltoid, serratus ...) are
 *     dropped. They are overlays on the whole muscle, and Strong's exercises
 *     resolve to whole muscles; shading a sub-region would claim a precision the
 *     data does not have.
 *
 * Network access lives here and only here -- src/ never fetches anything.
 *
 *   node scripts/make-body-paths.mjs            # fetch the pinned commit
 *   node scripts/make-body-paths.mjs ../MuscleMap   # or read a local checkout
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, '..', 'src', 'viz', 'bodyPaths.ts');

const REPO = 'melihcolpan/MuscleMap';
const COMMIT = 'cdcecf72ebdadb960930cc1c0515e618d2152398';
const DATA = 'Sources/MuscleMap/Data';

const VIEWS = [
  ['male', 'front', 'MaleFrontPaths.swift', 'maleFront'],
  ['male', 'back', 'MaleBackPaths.swift', 'maleBack'],
  ['female', 'front', 'FemaleFrontPaths.swift', 'femaleFront'],
  ['female', 'back', 'FemaleBackPaths.swift', 'femaleBack'],
];

/** MuscleMap slug (Swift case) -> region id written out. Anything absent is dropped. */
const KEEP = {
  chest: 'chest',
  abs: 'abs',
  obliques: 'obliques',
  biceps: 'biceps',
  triceps: 'triceps',
  forearm: 'forearm',
  deltoids: 'deltoids',
  rotatorCuff: 'rotator-cuff',
  trapezius: 'trapezius',
  upperBack: 'upper-back',
  lowerBack: 'lower-back',
  gluteal: 'gluteal',
  quadriceps: 'quadriceps',
  hamstring: 'hamstring',
  adductors: 'adductors',
  calves: 'calves',
  neck: 'neck',
  tibialis: 'tibialis',
  head: 'head',
  hair: 'hair',
  hands: 'hands',
  feet: 'feet',
  ankles: 'ankles',
  knees: 'knees',
};

const local = process.argv[2] ? resolve(process.argv[2]) : null;

async function source(file) {
  if (local) return readFileSync(resolve(local, DATA, file), 'utf8');
  const url = `https://raw.githubusercontent.com/${REPO}/${COMMIT}/${DATA}/${file}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return res.text();
}

function viewBoxes(swift) {
  const out = {};
  const re =
    /static let (\w+) = BodyViewBox\(\s*origin: CGPoint\(x: ([\d.]+), y: ([\d.]+)\),\s*size: CGSize\(width: ([\d.]+), height: ([\d.]+)\)/g;
  for (const m of swift.matchAll(re)) out[m[1]] = [m[2], m[3], m[4], m[5]].join(' ');
  return out;
}

function parts(swift) {
  const out = {};
  for (const block of swift.split('BodyPartPathData(').slice(1)) {
    const slug = block.match(/^\s*slug: \.(\w+)/)?.[1];
    if (!slug) continue;
    const id = KEEP[slug];
    if (!id) continue;
    const paths = [...block.matchAll(/"([Mm][^"]+)"/g)].map((m) => m[1]);
    if (paths.length === 0) continue;
    // Kept as separate strings, not joined into one `d`: the female views
    // open with a relative `m`, which is absolute only as the FIRST command of
    // a path. Concatenated, every outline after the first would drift.
    out[id] = [...(out[id] ?? []), ...paths];
  }
  return out;
}

const boxes = viewBoxes(await source('BodyPathData.swift'));
const body = { male: {}, female: {} };
for (const [figure, side, file, box] of VIEWS) {
  if (!boxes[box]) throw new Error('no viewBox ' + box);
  body[figure][side] = { viewBox: boxes[box], paths: parts(await source(file)) };
}

const header = `/**
 * Body outlines for the Recovery map. GENERATED by scripts/make-body-paths.mjs --
 * do not hand-edit; change the script and re-run it.
 *
 * Geometry from MuscleMap by Melih Colpan, MIT License, commit ${COMMIT.slice(0, 12)}.
 * https://github.com/${REPO} -- full licence text in NOTICE.md.
 *
 * Large, so the view imports it dynamically and it only loads on that tab.
 */

export type Figure = 'male' | 'female';
export type Side = 'front' | 'back';
export type BodyView = { viewBox: string; paths: Partial<Record<string, string[]>> };

`;
writeFileSync(
  OUT,
  header +
    'const BODY_PATHS: Record<Figure, Record<Side, BodyView>> = ' +
    JSON.stringify(body) +
    ';\n\nexport default BODY_PATHS;\n',
);
console.log('wrote', OUT);
